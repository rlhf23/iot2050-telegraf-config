    function mockResponse(data, status) {
        status = status || 200;
        var body = typeof data === 'string' ? data : JSON.stringify(data);
        return Promise.resolve({
            ok: status >= 200 && status < 300,
            status: status,
            statusText: status === 200 ? 'OK' : 'Error',
            json: function() { return Promise.resolve(typeof data === 'string' ? JSON.parse(data) : data); },
            text: function() { return Promise.resolve(typeof data === 'string' ? data : JSON.stringify(data)); }
        });
    }

    function handleMockFetch(url, options) {
        var path = typeof url === 'string' ? url : (url.url || '');
        path = path.replace(/^https?:\/\/[^/]+/, '');

        if (path === '/chronograf/health') {
            return mockResponse({message: 'ok'});
        }
        if (path === '/grafana/api/health') {
            return mockResponse({commit: 'abc123', database: 'ok', version: '11.0.0'});
        }
        if (path === '/influxdb/health') {
            return mockResponse({checks: [], message: 'ready for queries and writes', status: 'pass', version: '2.7.6'});
        }
        if (path === '/prometheus/-/healthy') {
            return mockResponse({status: 'success'});
        }
        if (path === '/telegraf/metrics') {
            return mockResponse('# HELP telegraf_metrics Telegraf metrics\n# TYPE telegraf_metrics counter\ntelegraf_metrics 1\n');
        }
        if (path === '/api/health') {
            return mockResponse({status: 'ok', service: 'config-generator'});
        }
        if (path === '/api/system-info') {
            mockSystemInfo.system_time = new Date().toLocaleString();
            mockSystemInfo.utc_time = new Date().toISOString().replace('T', ' ').split('.')[0] + ' UTC';
            return mockResponse(mockSystemInfo);
        }
        if (path === '/api/opcua/plc-time-stored') {
            return mockResponse(mockPlcTime);
        }
        if (path === '/api/config/telegraf') {
            return mockResponse(mockTelegrafConfig);
        }
        if (/^\/api\/containers\/([^/]+)\/logs$/.test(path)) {
            var container = path.match(/^\/api\/containers\/([^/]+)\/logs$/)[1];
            var logs = mockLogs[container] || 'No demo logs available for ' + container;
            return mockResponse(logs);
        }
        if (/^\/api\/containers\/([^/]+)\/restart$/.test(path)) {
            var match = path.match(/^\/api\/containers\/([^/]+)\/restart$/);
            return mockResponse({success: true, message: 'Container ' + match[1] + ' restarted (demo mode)'});
        }

        return originalFetch.apply(this, arguments);
    }

    function detectDemoMode() {
        var isDemo = false;

        try {
            var searchParams = new URLSearchParams(window.location.search);
            if (searchParams.get('demo') === '1') {
                isDemo = true;
            }
        } catch(e) {}

        if (window.location.protocol === 'file:') {
            isDemo = true;
        }

        if (window.DEMO_MODE === true) {
            isDemo = true;
        }

        return isDemo;
    }

    function addDemoBanner() {
        if (document.getElementById('demo-banner')) return;

        var banner = document.createElement('div');
        banner.id = 'demo-banner';
        banner.style.cssText = 'background:linear-gradient(135deg,#f59e0b,#d97706);color:white;text-align:center;padding:8px 16px;font-size:14px;font-weight:500;position:fixed;top:0;left:0;right:0;z-index:9999;box-shadow:0 2px 8px rgba(0,0,0,0.2);';
        banner.textContent = 'Demo Mode \u2014 This is a static preview with mock data. No live services are connected.';

        document.body.style.paddingTop = '40px';
        document.body.insertBefore(banner, document.body.firstChild);

        var existingBanner = document.querySelector('.demo-banner-spacer');
        if (!existingBanner) {
            var spacer = document.createElement('div');
            spacer.style.height = '40px';
            spacer.className = 'demo-banner-spacer';
            document.body.insertBefore(spacer, document.body.firstChild);
        }
    }

