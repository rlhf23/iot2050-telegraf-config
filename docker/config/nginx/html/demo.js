        externalLinks.forEach(function(link) {
            link.addEventListener('click', function(e) {
                e.preventDefault();
                var banner = document.getElementById('demo-banner');
                if (banner) {
                    var origText = banner.textContent;
                    banner.textContent = '\u26a0 External service links are disabled in demo mode';
                    banner.style.background = 'linear-gradient(135deg,#ef4444,#dc2626)';
                    setTimeout(function() {
                        banner.textContent = origText;
                        banner.style.background = 'linear-gradient(135deg,#f59e0b,#d97706)';
                    }, 2000);
                }
            });
        });

